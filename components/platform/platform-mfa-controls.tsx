"use client";

import { useEffect, useMemo, useState } from "react";
import Link from "next/link";

import { createSupabaseBrowserClient } from "@/lib/supabase/client";

type Enrollment = { factorId: string; qr: string; secret: string };

export function PlatformMfaControls() {
  const supabase = useMemo(() => createSupabaseBrowserClient(), []);
  const [loading, setLoading] = useState(true);
  const [busy, setBusy] = useState(false);
  const [factorId, setFactorId] = useState<string | null>(null);
  const [enrollment, setEnrollment] = useState<Enrollment | null>(null);
  const [code, setCode] = useState("");
  const [message, setMessage] = useState("");

  useEffect(() => {
    let active = true;
    (async () => {
      const { data, error } = await supabase.auth.mfa.listFactors();
      if (!active) return;
      if (error) setMessage("Unable to load your authenticator. Sign in again and retry.");
      else setFactorId(data.totp.find((factor) => factor.status === "verified")?.id ?? null);
      setLoading(false);
    })();
    return () => { active = false; };
  }, [supabase]);

  async function enroll() {
    if (busy) return;
    setBusy(true);
    setMessage("");
    try {
      const { data, error } = await supabase.auth.mfa.enroll({
        factorType: "totp",
        friendlyName: "MunshiOS platform owner",
      });
      if (error || !data?.totp) {
        setMessage("Could not start setup. Check that TOTP MFA is enabled in Supabase Auth.");
        return;
      }
      setEnrollment({ factorId: data.id, qr: data.totp.qr_code, secret: data.totp.secret });
    } catch {
      setMessage("Unable to start authenticator setup.");
    } finally {
      setBusy(false);
    }
  }

  async function verify() {
    if (busy) return;
    const selectedFactor = factorId ?? enrollment?.factorId;
    if (!selectedFactor || !/^[0-9]{6}$/.test(code.trim())) {
      setMessage("Enter the current 6-digit code from your authenticator app.");
      return;
    }
    setBusy(true);
    setMessage("");
    try {
      const { data: challenge, error: challengeError } = await supabase.auth.mfa.challenge({
        factorId: selectedFactor,
      });
      if (challengeError || !challenge) {
        setMessage("Could not request MFA verification. Retry with a fresh code.");
        return;
      }
      const { error: verificationError } = await supabase.auth.mfa.verify({
        factorId: selectedFactor,
        challengeId: challenge.id,
        code: code.trim(),
      });
      if (verificationError) {
        setMessage("The code was invalid or expired. Enter a new code.");
        return;
      }
      window.location.assign("/platform");
    } catch {
      setMessage("MFA verification failed. Please retry.");
    } finally {
      setBusy(false);
    }
  }

  if (loading) return <p className="text-sm text-slate-600">Loading authenticator settings…</p>;

  return (
    <div className="space-y-5">
      {factorId ? (
        <p className="text-sm text-slate-700">
          Your authenticator is enrolled. Verify a fresh code to enter the admin portal and authorize changes for ten minutes.
        </p>
      ) : (
        <div className="space-y-3 text-sm text-slate-700">
          <p>Set up an authenticator app to protect the MunshiOS owner account. Admin access is blocked until setup is verified.</p>
          {!enrollment ? (
            <button type="button" disabled={busy} onClick={enroll} className="rounded-lg bg-emerald-700 px-4 py-2 font-semibold text-white disabled:opacity-50">
              {busy ? "Setting up…" : "Set up authenticator"}
            </button>
          ) : (
            <div className="space-y-3 rounded-xl border border-slate-200 bg-slate-50 p-4">
              <p>Scan this QR code with your authenticator app or enter the setup key manually.</p>
              {/* QR is generated by Supabase Auth and only ever rendered in this owner session. */}
              {/* eslint-disable-next-line @next/next/no-img-element */}
              <img src={enrollment.qr} alt="Authenticator enrollment QR code" className="size-44 rounded bg-white p-2" />
              <div>
                <span className="block text-xs text-slate-600">Manual setup key</span>
                <code className="break-all font-mono text-xs text-slate-900">{enrollment.secret}</code>
              </div>
            </div>
          )}
        </div>
      )}
      {(factorId || enrollment) && (
        <form onSubmit={(event) => { event.preventDefault(); void verify(); }} className="space-y-3">
          <label htmlFor="platform-totp" className="block text-sm font-medium text-slate-800">Authenticator code</label>
          <input id="platform-totp" type="text" inputMode="numeric" pattern="[0-9]{6}" maxLength={6} autoComplete="one-time-code"
            value={code} onChange={(event) => setCode(event.target.value.replace(/[^0-9]/g, "").slice(0, 6))}
            disabled={busy} required className="h-11 w-full max-w-xs rounded-xl border border-slate-300 px-3 text-base tracking-widest" />
          <button type="submit" disabled={busy || code.length !== 6} className="block rounded-lg bg-emerald-700 px-4 py-2 text-sm font-semibold text-white disabled:opacity-50">
            {busy ? "Verifying…" : "Verify and open admin"}
          </button>
        </form>
      )}
      {message && <p role="alert" className="text-sm font-medium text-red-700">{message}</p>}
      <p className="text-xs text-slate-500">Never share your authenticator setup key or security code.</p>
      <Link href="/" className="inline-block text-xs text-emerald-700 underline">Return to MunshiOS</Link>
    </div>
  );
}
